CREATE TABLE accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','LIBRARIAN','MEMBER')),
 status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE','BLACKLISTED','CLOSED')),
 protected_account BOOLEAN NOT NULL DEFAULT FALSE, archived BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE authors (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL, archived BOOLEAN NOT NULL DEFAULT FALSE);
CREATE TABLE titles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, isbn VARCHAR(32) NOT NULL UNIQUE,
 title VARCHAR(200) NOT NULL, genre VARCHAR(80) NOT NULL, publisher VARCHAR(120) NOT NULL,
 description VARCHAR(2000) NOT NULL, archived BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE title_authors (title_id BIGINT NOT NULL REFERENCES titles, author_id BIGINT NOT NULL REFERENCES authors, PRIMARY KEY(title_id,author_id));
CREATE TABLE copies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, barcode VARCHAR(40) NOT NULL UNIQUE,
 title_id BIGINT NOT NULL REFERENCES titles, status VARCHAR(24) NOT NULL CHECK (status IN ('AVAILABLE','LOANED','HELD','LOST','REFERENCE_ONLY')),
 archived BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE loans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, borrower_id BIGINT NOT NULL REFERENCES accounts,
 copy_id BIGINT NOT NULL REFERENCES copies, issue_date DATE NOT NULL, due_date DATE NOT NULL,
 return_date DATE, renewals INTEGER NOT NULL DEFAULT 0, final_fine NUMERIC(10,2),
 CHECK(due_date >= issue_date), CHECK(return_date IS NULL OR return_date >= issue_date), CHECK(renewals BETWEEN 0 AND 1)
);
CREATE UNIQUE INDEX one_active_loan_per_copy ON loans(copy_id) WHERE return_date IS NULL;
CREATE INDEX loans_borrower ON loans(borrower_id);
CREATE TABLE reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, borrower_id BIGINT NOT NULL REFERENCES accounts,
 title_id BIGINT NOT NULL REFERENCES titles, copy_id BIGINT REFERENCES copies,
 status VARCHAR(24) NOT NULL CHECK(status IN ('WAITING','READY','FULFILLED','CANCELLED','EXPIRED')),
 created_at TIMESTAMPTZ NOT NULL, expires_at TIMESTAMPTZ,
 CHECK(status <> 'READY' OR (copy_id IS NOT NULL AND expires_at IS NOT NULL))
);
CREATE UNIQUE INDEX one_active_reservation ON reservations(borrower_id,title_id) WHERE status IN ('WAITING','READY');
CREATE UNIQUE INDEX one_hold_per_copy ON reservations(copy_id) WHERE status = 'READY';
CREATE INDEX reservation_queue ON reservations(title_id,created_at,id);
CREATE TABLE activities (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor VARCHAR(120) NOT NULL, message VARCHAR(400) NOT NULL, created_at TIMESTAMPTZ NOT NULL);
